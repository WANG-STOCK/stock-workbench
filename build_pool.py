def build_pool():
    pool = []
    for track, rows in GROUPS.items():
        sector = SECTOR_OF[track]
        for code, name, grade, note in rows:
            if code in DROP:
                continue
            code = CODE_FIX.get(code, code)
            name = NAME_FIX.get(code, name)
            pool.append({"code": code, "name": name, "track": track,
                         "sector": sector, "grade": grade, "note": note})
    return pool


def validate(pool):
    codes = [p["code"] for p in pool]
    # 重复检查
    seen, dups = set(), []
    for c in codes:
        if c in seen:
            dups.append(c)
        seen.add(c)
    if dups:
        print("[重复代码]", sorted(set(dups)))

    # 主板前缀校验
    bad_prefix = []
    for c in codes:
        m, num = c[:2], c[2:]
        if not (num.isdigit() and len(num) == 6):
            bad_prefix.append(c); continue
        if m == "sh" and num[:3] in ("600", "601", "603", "605", "604", "602") and num[:3] != "688":
            continue
        if m == "sz" and num[:3] in ("000", "001", "002", "003") and num[:3] not in ("300", "301"):
            continue
        bad_prefix.append(c)
    if bad_prefix:
        print("[非主板前缀/格式错误]", sorted(set(bad_prefix)))

    # 腾讯实时接口逐只校验
    names = {}
    chunk = 50
    for i in range(0, len(codes), chunk):
        sub = codes[i:i+chunk]
        try:
            rt = ds.fetch_realtime(sub)
        except Exception as e:
            print("[接口异常]", e); continue
        for c in sub:
            v = rt.get(c)
            if v and v.get("name"):
                names[c] = v["name"]
    # 报告无名称的（可能退市/代码错）
    invalid = [c for c in codes if c not in names]
    if invalid:
        print("[腾讯无返回/疑似错码]", invalid)
    # 名称不一致提示（仅提示，不强制改）
    for p in pool:
        tn = names.get(p["code"])
        if tn and tn != p["name"]:
            print(f"[名称不一致] {p['code']} 本端={p['name']} 腾讯={tn}")
    return names


